    st.markdown(f'<div class="section-heading">{copy["overview"]}</div>', unsafe_allow_html=True)
    st.markdown(
        f'<p class="section-caption">{copy["overview_caption"]}</p>',
        unsafe_allow_html=True,
    )

    tasks = load_tasks(account["id"])
    today = date.today()
    for task in tasks:
        task["days_left"] = (date.fromisoformat(task["due_date"]) - today).days
        urgency_score = 10 / max(task["days_left"], 0.5)
        task["score"] = round((urgency_score * 0.4) + (task["importance"] * 0.6), 2)

    pending_tasks = [task for task in tasks if not task["completed"]]
    if bool(account["notifications"]) and any(
        task["days_left"] <= 1 for task in pending_tasks
    ):
        st.warning(
            " · ".join(
                f'{task["title"]}: {copy["overdue"].format(days=abs(task["days_left"]))}'
                if task["days_left"] < 0
                else f'{task["title"]}: {copy["due_today"]}'
                if task["days_left"] == 0
                else f'{task["title"]}: {copy["due_in"].format(days=task["days_left"])}'
                for task in pending_tasks
                if task["days_left"] <= 1
            )
        )

    if tasks:
        sorted_tasks = sorted(
            tasks,
            key=lambda task: (bool(task["completed"]), -task["score"]),
        )
        metric_columns = st.columns(3)
        metric_columns[0].metric(copy["total"], len(tasks))
        metric_columns[1].metric(copy["pending"], len(pending_tasks))
        metric_columns[2].metric(copy["completed"], len(tasks) - len(pending_tasks))
        nearest_deadline = min(
            (task["days_left"] for task in pending_tasks),
            default=None,
        )
        if nearest_deadline is not None:
            st.caption(
                f'{copy["nearest"]}: {copy["due_in"].format(days=nearest_deadline)}'
                if nearest_deadline > 0
                else copy["due_today"]
                if nearest_deadline == 0
                else copy["overdue"].format(days=abs(nearest_deadline))
            )

        for index, task in enumerate(sorted_tasks, 1):
            with st.container(border=True):
                title_column, score_column = st.columns([4, 1])
