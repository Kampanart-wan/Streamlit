DATABASE_PATH = Path(__file__).with_name("taskflow.sqlite3")


def load_database_url():
    try:
        database_settings = st.secrets.get("database", {})
    except StreamlitSecretNotFoundError:
        return None
    database_url = database_settings.get("url")
    if database_url and not database_url.startswith(("postgresql://", "postgres://")):
        raise ValueError("The database URL must be a PostgreSQL connection string.")
    return database_url


DATABASE_URL = load_database_url()


@contextmanager
def database_connection():
    if DATABASE_URL:
        import psycopg2
        from psycopg2.extras import RealDictCursor

        connection = psycopg2.connect(
            DATABASE_URL,
            cursor_factory=RealDictCursor,
            sslmode="require",
        )
    else:
        connection = sqlite3.connect(DATABASE_PATH, timeout=10)
        connection.row_factory = sqlite3.Row
    try:
        with connection:
            yield connection
    finally:
        connection.close()


def execute_query(connection, query, parameters=()):
    if DATABASE_URL:
        cursor = connection.cursor()
        cursor.execute(query.replace("?", "%s"), parameters)
        return cursor
    return connection.execute(query, parameters)


def initialize_database():
    with database_connection() as connection:
        if DATABASE_URL:
            execute_query(
                connection,
                """
                CREATE TABLE IF NOT EXISTS accounts (
                    id TEXT PRIMARY KEY,
                    email TEXT NOT NULL,
                    name TEXT NOT NULL,
                    language TEXT NOT NULL DEFAULT 'ไทย',
                    theme TEXT NOT NULL DEFAULT 'Indigo',
                    notifications BOOLEAN NOT NULL DEFAULT TRUE
                )
                """,
            )
            execute_query(
                connection,
                """
                CREATE TABLE IF NOT EXISTS tasks (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
                    title TEXT NOT NULL,
                    due_date TEXT NOT NULL,
                    importance INTEGER NOT NULL CHECK (importance BETWEEN 1 AND 5),
                    completed BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """,
            )
        else:
            execute_query(
                connection,
                """
                CREATE TABLE IF NOT EXISTS accounts (
                    id TEXT PRIMARY KEY,
                    email TEXT NOT NULL,
                    name TEXT NOT NULL,
                    language TEXT NOT NULL DEFAULT 'ไทย',
                    theme TEXT NOT NULL DEFAULT 'Indigo',
                    notifications INTEGER NOT NULL DEFAULT 1
                )
                """,
            )
            execute_query(
                connection,
                """
                CREATE TABLE IF NOT EXISTS tasks (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
                    title TEXT NOT NULL,
                    due_date TEXT NOT NULL,
                    importance INTEGER NOT NULL CHECK (importance BETWEEN 1 AND 5),
                    completed INTEGER NOT NULL DEFAULT 0,
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """,
            )


def upsert_account(account_id, email, name):
    with database_connection() as connection:
        execute_query(
            connection,
            """
            INSERT INTO accounts (id, email, name) VALUES (?, ?, ?)
            ON CONFLICT(id) DO UPDATE SET email = excluded.email, name = excluded.name
            """,
            (account_id, email, name),
        )
        return dict(
            execute_query(
                connection, "SELECT * FROM accounts WHERE id = ?", (account_id,)
            ).fetchone()
        )


def save_preferences(account_id, language, theme, notifications):
    with database_connection() as connection:
        execute_query(
            connection,
            """
            UPDATE accounts SET language = ?, theme = ?, notifications = ?
            WHERE id = ?
            """,
            (language, theme, bool(notifications), account_id),
        )


def load_tasks(account_id):
    with database_connection() as connection:
        return [
            dict(row)
            for row in execute_query(
                connection,
                "SELECT * FROM tasks WHERE account_id = ? ORDER BY id DESC",
                (account_id,),
            ).fetchall()
        ]


def add_task(account_id, title, days_until_due, importance):
    due_date = (date.today() + timedelta(days=days_until_due)).isoformat()
    with database_connection() as connection:
        execute_query(
            connection,
            """
            INSERT INTO tasks (account_id, title, due_date, importance)
            VALUES (?, ?, ?, ?)
            """,
            (account_id, title, due_date, importance),
        )


def update_task(task_id, account_id, completed):
    with database_connection() as connection:
        execute_query(
            connection,
            "UPDATE tasks SET completed = ? WHERE id = ? AND account_id = ?",
            (bool(completed), task_id, account_id),
        )


def delete_task(task_id, account_id):
    with database_connection() as connection:
        execute_query(
            connection,
            "DELETE FROM tasks WHERE id = ? AND account_id = ?",
            (task_id, account_id),
        )


def clear_tasks(account_id):
    with database_connection() as connection:
        execute_query(
            connection, "DELETE FROM tasks WHERE account_id = ?", (account_id,)
        )


